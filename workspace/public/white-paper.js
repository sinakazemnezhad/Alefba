function applyLang(lang) {
  const dict = WP[lang] || WP.fa;
  const html = document.documentElement;
  html.lang = lang === "en" ? "en" : "fa";
  html.dir = lang === "en" ? "ltr" : "rtl";
  html.dataset.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] != null) el.innerHTML = dict[key];
  });

  const btn = document.getElementById("lang-btn");
  if (btn) btn.textContent = dict.langBtn;
  if (dict.title) document.title = dict.title;
  if (window.AlefbaSeo && dict.pageDescription) {
    window.AlefbaSeo.applySeo({
      path: "/white-paper.html",
      titles: { fa: WP.fa.title, en: WP.en.title },
      descriptions: { fa: WP.fa.pageDescription, en: WP.en.pageDescription },
      ogImage: "/og-share.svg",
    });
  }
  localStorage.setItem("alefba-lang", lang);
}

function initProgress() {
  const bar = document.getElementById("wp-progress-bar");
  if (!bar) return;
  const onScroll = () => {
    const doc = document.documentElement;
    const max = doc.scrollHeight - doc.clientHeight;
    const pct = max > 0 ? (doc.scrollTop / max) * 100 : 0;
    bar.style.width = `${pct}%`;
  };
  window.addEventListener("scroll", onScroll, { passive: true });
  onScroll();
}

function initRail() {
  const links = [...document.querySelectorAll("#wp-rail-nav a")];
  const sections = links
    .map((a) => document.querySelector(a.getAttribute("href")))
    .filter(Boolean);
  if (!links.length || !sections.length) return;

  const io = new IntersectionObserver(
    (entries) => {
      const visible = entries
        .filter((e) => e.isIntersecting)
        .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
      if (!visible) return;
      const id = `#${visible.target.id}`;
      links.forEach((a) => a.classList.toggle("is-active", a.getAttribute("href") === id));
    },
    { rootMargin: "-20% 0px -55% 0px", threshold: [0.1, 0.25, 0.5] }
  );
  sections.forEach((s) => io.observe(s));
}

function initTools() {
  document.getElementById("print-wp")?.addEventListener("click", () => window.print());
  document.getElementById("copy-cite")?.addEventListener("click", async () => {
    const lang = document.documentElement.dataset.lang || "fa";
    const text = `${WP[lang].cite}\n${location.href.split("?")[0]}`;
    try {
      await navigator.clipboard.writeText(text);
    } catch {
      const ta = document.createElement("textarea");
      ta.value = text;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand("copy");
      ta.remove();
    }
    const btn = document.getElementById("copy-cite");
    if (btn) {
      const prev = btn.textContent;
      btn.textContent = WP[lang]["tool.cited"];
      setTimeout(() => {
        btn.textContent = prev;
      }, 1600);
    }
  });
}

function initMenu() {
  const btn = document.getElementById("menu-btn");
  const panel = document.getElementById("nav-panel");
  if (!btn || !panel) return;

  const close = () => {
    document.body.classList.remove("nav-open");
    panel.hidden = true;
    btn.setAttribute("aria-expanded", "false");
  };

  const open = () => {
    document.body.classList.add("nav-open");
    panel.hidden = false;
    btn.setAttribute("aria-expanded", "true");
  };

  btn.addEventListener("click", () => {
    if (panel.hidden) open();
    else close();
  });

  panel.querySelectorAll("a").forEach((a) => {
    a.addEventListener("click", () => close());
  });

  document.addEventListener("keydown", (ev) => {
    if (ev.key === "Escape") close();
  });
}

