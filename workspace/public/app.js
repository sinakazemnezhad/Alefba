const ROLE_BY_LANE = {
  invest: "angel",
  participate: "builder",
  donate: "donor",
};

const FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹";

function getLang() {
  const lang = document.documentElement.dataset.lang || document.documentElement.lang;
  return lang === "fa" ? "fa" : "en";
}

function toFaDigits(str) {
  return String(str).replace(/\d/g, (d) => FA_DIGITS[Number(d)]);
}

function formatNumber(n, lang = getLang()) {
  const num = Number(n) || 0;
  if (lang === "fa") return toFaDigits(num.toLocaleString("fa-IR"));
  return num.toLocaleString("en-US");
}

function formatPercent(n, lang = getLang()) {
  const v = Math.round(Number(n) || 0);
  if (lang === "fa") return `${toFaDigits(String(v))}٪`;
  return `${v}%`;
}

function formatThermoSummary(pledged, goal, pct, lang = getLang()) {
  if (lang === "fa") {
    return `${money(pledged, lang)} از ${money(goal, lang)}، ${formatPercent(pct, lang)}`;
  }
  return `${money(pledged, lang)} / ${money(goal, lang)} · ${formatPercent(pct, lang)}`;
}

function applyPersianNumeralsInDom() {
  const lang = getLang();
  document.querySelectorAll("[data-pct]").forEach((el) => {
    const raw = el.getAttribute("data-pct");
    if (!raw) return;
    el.textContent = formatPercent(raw, lang);
  });
}

function money(n, lang = getLang()) {
  const v = formatNumber(n, lang);
  if (lang === "fa") return `${v} دلار`;
  return `$${v}`;
}

function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  const html = document.documentElement;
  html.lang = lang === "fa" ? "fa" : "en";
  html.dir = lang === "fa" ? "rtl" : "ltr";
  html.dataset.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] != null) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] != null) el.setAttribute("placeholder", dict[key]);
  });

  const btn = document.getElementById("lang-btn");
  if (btn) btn.textContent = dict.langBtn;

  if (dict.pageTitle) document.title = dict.pageTitle;

  applyPersianNumeralsInDom();

  renderTicker(dict.ticker);
  updateShareLinks();
  const active = document.querySelector(".sample-key.is-on")?.getAttribute("data-sample") || "code";
  showSample(active);
  localStorage.setItem("alefba-lang", lang);
}

function renderTicker(items) {
  const track = document.getElementById("live-track");
  if (!track || !items?.length) return;
  const chunk = items
    .map((t, i) => (i % 2 === 0 ? `<strong>${t}</strong>` : `<span>${t}</span>`))
    .join("<span aria-hidden='true'> · </span>");
  track.innerHTML = `${chunk}<span aria-hidden='true'> · </span>${chunk}`;
}

function setLane(lane, extras = {}) {
  const field = document.getElementById("lane-field");
  const role = document.getElementById("role-field");
  const amountWrap = document.getElementById("amount-wrap");
  const amount = document.getElementById("amount-field");
  const tier = document.getElementById("tier-field");
  const note = document.getElementById("note-field");

  if (field) field.value = lane;
  document.querySelectorAll("[data-set-lane]").forEach((btn) => {
    btn.classList.toggle("is-on", btn.getAttribute("data-set-lane") === lane);
  });

  if (role) {
    if (extras.role) role.value = extras.role;
    else if (ROLE_BY_LANE[lane]) role.value = ROLE_BY_LANE[lane];
  }
  if (amountWrap) amountWrap.hidden = !(lane === "invest" || lane === "donate");
  if (amount && extras.amount != null) amount.value = extras.amount;
  if (tier) tier.value = extras.tier || "";
  if (note && extras.note) note.value = extras.note;

  document.querySelectorAll(".tier").forEach((el) => {
    const on =
      el.getAttribute("data-lane") === lane &&
      (!extras.tier || el.getAttribute("data-tier") === extras.tier);
    el.classList.toggle("is-on", Boolean(extras.tier) && on);
  });
}

function renderStats(stats) {
  const lang = getLang();
  const c = stats?.counts || { invest: 0, participate: 0, donate: 0 };
  const set = (id, v) => {
    const el = document.getElementById(id);
    if (el) el.textContent = formatNumber(v ?? 0, lang);
  };
  set("stat-invest", c.invest);
  set("stat-participate", c.participate);
  set("stat-donate", c.donate);

  const pledged = stats?.pledgedUsd ?? 0;
  const goal = stats?.goalUsd ?? 50000;
  const pct = stats?.progressPct ?? 0;
  const summaryEl = document.getElementById("thermo-summary");
  const fill = document.getElementById("thermo-fill");
  const bar = document.getElementById("thermo-bar");
  if (summaryEl) summaryEl.textContent = formatThermoSummary(pledged, goal, pct, lang);
  if (fill) fill.style.width = `${pct}%`;
  if (bar) bar.setAttribute("aria-valuenow", String(pct));

  const wall = document.getElementById("supporter-wall");
  if (!wall) return;
  const rows = (stats?.wall || []).filter((w) => w.lane);
  if (!rows.length) {
    wall.innerHTML = `<li class="wall-empty">${I18N[lang]["wall.empty"]}</li>`;
    return;
  }
  wall.innerHTML = rows
    .map((w) => {
      const badge = w.founding ? `<span class="wall-badge">${escapeHtml(I18N[lang]["wall.founding"])}</span>` : "";
      return `<li>${escapeHtml(w.name)}${badge}<em>${escapeHtml(w.lane)}</em></li>`;
    })
    .join("");
}

function captureUtm() {
  const params = new URLSearchParams(location.search);
  const ref = params.get("ref") || params.get("utm_source");
  if (ref) {
    try {
      localStorage.setItem("alefba-ref", ref.slice(0, 64));
    } catch {
      /* ignore */
    }
  }
  return localStorage.getItem("alefba-ref") || "";
}

function trackPageView(page) {
  const ref = captureUtm();
  const payload = { page: page || location.pathname, ref, at: new Date().toISOString() };
  try {
    const key = "alefba-views";
    const prev = JSON.parse(localStorage.getItem(key) || "[]");
    prev.push(payload);
    localStorage.setItem(key, JSON.stringify(prev.slice(-50)));
  } catch {
    /* ignore */
  }
}

function initCharterBar() {
  const bar = document.getElementById("charter-bar");
  if (!bar) return;
  const show = () => {
    const y = window.scrollY || document.documentElement.scrollTop;
    bar.classList.toggle("is-visible", y > 280);
  };
  window.addEventListener("scroll", show, { passive: true });
  show();
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

async function refreshStats() {
  try {
    const res = await fetch("/api/stats", { cache: "no-store" });
    if (!res.ok) throw new Error("stats_failed");
    renderStats(await res.json());
  } catch {
    const local = JSON.parse(localStorage.getItem("alefba-community-interest") || "[]");
    const counts = { invest: 0, participate: 0, donate: 0 };
    let pledgedUsd = 0;
    const wall = [];
    for (const r of local) {
      const lane = ["invest", "participate", "donate"].includes(r.lane) ? r.lane : "participate";
      counts[lane] += 1;
      if (lane === "donate") {
        const m = String(r.amount || "").replace(/,/g, "").match(/(\d+(?:\.\d+)?)\s*(k)?/i);
        if (m) pledgedUsd += Number(m[1]) * (m[2] ? 1000 : 1);
      }
      wall.push({ name: String(r.name || "Anon").split(/\s+/)[0], lane });
    }
    const goalUsd = 50000;
    renderStats({
      counts,
      pledgedUsd: Math.round(pledgedUsd),
      goalUsd,
      progressPct: pledgedUsd <= 0 ? 0 : Math.max(1, Math.min(100, Math.round((pledgedUsd / goalUsd) * 100))),
      wall: wall.reverse().slice(0, 40),
    });
  }
}

