function initSample() {
  const theater = document.querySelector(".sample-theater");
  const keys = [...document.querySelectorAll(".sample-key")];
  keys.forEach((btn, idx) => {
    btn.tabIndex = btn.classList.contains("is-on") ? 0 : -1;
    btn.addEventListener("click", () => {
      samplePaused = true;
      showSample(btn.getAttribute("data-sample"));
      setTimeout(() => {
        samplePaused = false;
      }, 12000);
    });
    btn.addEventListener("keydown", (ev) => {
      if (ev.key !== "ArrowRight" && ev.key !== "ArrowLeft" && ev.key !== "Home" && ev.key !== "End") return;
      ev.preventDefault();
      samplePaused = true;
      const rtl = document.documentElement.dir === "rtl";
      let next = idx;
      if (ev.key === "Home") next = 0;
      else if (ev.key === "End") next = keys.length - 1;
      else if (ev.key === "ArrowRight") next = (idx + (rtl ? -1 : 1) + keys.length) % keys.length;
      else if (ev.key === "ArrowLeft") next = (idx + (rtl ? 1 : -1) + keys.length) % keys.length;
      showSample(keys[next].getAttribute("data-sample"));
      keys[next].focus();
    });
    btn.addEventListener("focus", () => {
      samplePaused = true;
    });
  });
  theater?.addEventListener("mouseenter", () => {
    samplePaused = true;
  });
  theater?.addEventListener("mouseleave", () => {
    samplePaused = false;
  });
  theater?.addEventListener("focusin", () => {
    samplePaused = true;
  });
  theater?.addEventListener("focusout", (ev) => {
    if (!theater.contains(ev.relatedTarget)) samplePaused = false;
  });
  showSample("code");
  startSampleCycle();
}

